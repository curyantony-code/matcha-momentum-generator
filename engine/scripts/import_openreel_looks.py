"""Import OpenReel Video's colour presets (packages/core/src/video/filter-presets.ts, MIT, Augustus Otu and
Contributors) as Matcha Momentum Generator looks. Reads the TypeScript as TEXT (nothing of OpenReel is run) and writes:

  engine/reelengine/data/openreel_looks.json   the presets, for the engine (looks.py turns them into ffmpeg)
  app/src/shared/openreel-looks.ts             the names, groups and tile previews, for the app

Usage: python engine/scripts/import_openreel_looks.py [path/to/openreel-video]   (default ~/matcha/_reference/openreel-video)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
EFFECT_TYPES = {"brightness", "contrast", "saturation", "hue", "blur", "sharpen", "vignette", "grain"}
CATEGORIES = {"cinematic": "Cinematic", "vintage": "Vintage", "mood": "Mood", "color": "Colour", "stylized": "Stylized"}


def ts_array_to_json(ts: str) -> list:
    body = ts[ts.index("FILTER_PRESETS: FilterPreset[] = [") + len("FILTER_PRESETS: FilterPreset[] = "):]
    body = body[: body.index("];\n\nexport const FILTER_CATEGORIES") + 1]
    body = re.sub(r"(?m)^(\s*)([A-Za-z_]\w*)\s*:", r'\1"\2":', body)          # keys at line starts
    body = re.sub(r"([{,]\s*)([A-Za-z_]\w*)\s*:", r'\1"\2":', body)            # keys inside { a: 1, b: 2 }
    body = re.sub(r",(\s*[}\]])", r"\1", body)                                 # trailing commas
    return json.loads(body)


def checked(presets: list) -> list:
    out = []
    for p in presets:
        assert re.fullmatch(r"[a-z0-9-]{1,48}", p["id"]) and p["category"] in CATEGORIES, p.get("id")
        for e in p["effects"]:
            assert e["type"] in EFFECT_TYPES, (p["id"], e["type"])
            assert all(isinstance(v, (int, float, bool, str)) for v in e["params"].values()), (p["id"], e)
        out.append({k: p[k] for k in ("id", "name", "category", "description", "effects")})
    return out


def css_preview(effects: list) -> str:
    """A CSS filter close to the look, only for the small tiles in the app."""
    parts = []
    for e in effects:
        t, q = e["type"], e["params"]
        if t == "brightness":
            parts.append(f"brightness({1 + q['value']:.2f})")
        elif t == "contrast":
            parts.append(f"contrast({q['value']:.2f})")
        elif t == "saturation":
            parts.append(f"saturate({q['value']:.2f})")
        elif t == "hue":
            parts.append(f"hue-rotate({q['rotation']:g}deg)")
        elif t == "blur":
            parts.append(f"blur({min(2.0, q['radius'] * 0.6):.1f}px)")
    return " ".join(parts) or "none"


def main() -> None:
    src = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / "openreel-video")
    ts = (src / "packages/core/src/video/filter-presets.ts").read_text(encoding="utf-8")
    presets = checked(ts_array_to_json(ts))
    data = REPO / "engine/reelengine/data/openreel_looks.json"
    data.parent.mkdir(exist_ok=True)
    data.write_text(json.dumps({"source": "OpenReel Video filter-presets.ts (MIT, Augustus Otu and Contributors)",
                                "presets": presets}, indent=1) + "\n", encoding="utf-8")
    rows = ",\n".join(
        f"  {{ key: {json.dumps(p['id'])}, label: {json.dumps(p['name'])}, group: {json.dumps(CATEGORIES[p['category']])}, "
        f"hint: {json.dumps(p['description'])}, css: {json.dumps(css_preview(p['effects']))} }}"
        for p in presets)
    (REPO / "app/src/shared/openreel-looks.ts").write_text(
        "// Generated by engine/scripts/import_openreel_looks.py from OpenReel Video's filter-presets.ts\n"
        "// (MIT, Augustus Otu and Contributors). Do not edit by hand: run the script again.\n\n"
        "export interface OpenReelLook { key: string; label: string; group: string; hint: string; css: string }\n\n"
        f"export const OPENREEL_LOOKS: readonly OpenReelLook[] = [\n{rows}\n]\n", encoding="utf-8")
    names = ",\n".join(f"  {{ key: {json.dumps(p['id'])}, label: {json.dumps(p['name'])} }}" for p in presets)
    (REPO / "ai/src/openreel-looks.generated.ts").write_text(
        "// Generated by engine/scripts/import_openreel_looks.py from OpenReel Video's filter-presets.ts\n"
        "// (MIT, Augustus Otu and Contributors). Do not edit by hand: run the script again.\n\n"
        f"export const OPENREEL_LOOK_NAMES = [\n{names}\n] as const;\n", encoding="utf-8")
    print(f"{len(presets)} presets -> {data.relative_to(REPO)}, app/src/shared/openreel-looks.ts, ai/src/openreel-looks.generated.ts")


if __name__ == "__main__":
    main()
